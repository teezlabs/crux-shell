#!/usr/bin/env python3
# Rebuilds Assets/Fonts/MaterialSymbolsRounded.ttf and Commons/SymbolCodepoints.js from the full
# Material Symbols Rounded variable font, keeping only ICONS. Add a name here and rerun to use a new icon.
# Usage: subset-symbols.py <MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf> <its .codepoints file>
import io, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ICONS = """
wifi wifi_off bluetooth bluetooth_disabled bluetooth_connected mic mic_off nightlight bedtime coffee
bolt eco balance speed energy_savings_leaf notifications notifications_off do_not_disturb_on
volume_up volume_down volume_mute volume_off brightness_6 light_mode screenshot_region screenshot_monitor
radio_button_checked colorize wallpaper settings lock power_settings_new close chevron_right schedule
partly_cloudy_day partly_cloudy_night cloud rainy sunny clear_night foggy weather_snowy thunderstorm
play_arrow pause skip_next skip_previous memory thermostat storage developer_board content_paste logout
refresh more_horiz clear_all music_note headphones speaker person visibility visibility_off dark_mode
palette search check expand_more air water_drop sports_esports vpn_lock vpn_key_off dns
open_in_new
""".split()

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
font_in, points_in = sys.argv[1], sys.argv[2]
points = dict(line.split() for line in open(points_in) if line.strip())
missing = [n for n in ICONS if n not in points]
if missing:
    sys.exit("not in the font: " + " ".join(missing))

font = TTFont(font_in)
# Only fill and weight vary at runtime; grade and optical size are pinned.
font = instancer.instantiateVariableFont(font, {"GRAD": 0, "opsz": 24})
# Reload from bytes: the instancer leaves lazily loaded tables the subsetter can't walk.
buf = io.BytesIO()
font.save(buf)
font = TTFont(io.BytesIO(buf.getvalue()))
opts = subset.Options()
# Icons are addressed by codepoint, so the name ligatures go.
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(points[n], 16) for n in ICONS])
sub.subset(font)
font.save(os.path.join(root, "Assets/Fonts/MaterialSymbolsRounded.ttf"))

with open(os.path.join(root, "Commons/SymbolCodepoints.js"), "w") as js:
    js.write(".pragma library\n\n// Generated by packaging/subset-symbols.py: Material Symbols name -> codepoint.\nvar map = {\n")
    js.write(",\n".join('  "%s": 0x%s' % (n, points[n]) for n in ICONS))
    js.write("\n};\n")
print("ok", len(ICONS), "icons")
